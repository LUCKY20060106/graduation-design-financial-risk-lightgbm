package com.risk.prediction.service;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.risk.prediction.entity.PredictionResult;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.Map;

@Service
public class PdfExportService {

    public byte[] generatePredictionPdf(PredictionResult result) throws DocumentException, IOException {
        Document document = new Document(PageSize.A4);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PdfWriter.getInstance(document, out);

        document.open();

        // 标题
        Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 22);
        Paragraph title = new Paragraph("Financial Risk Diagnostic Report", titleFont);
        title.setAlignment(Element.ALIGN_CENTER);
        title.setSpacingAfter(20);
        document.add(title);

        // 基本信息表格
        PdfPTable infoTable = new PdfPTable(2);
        infoTable.setWidthPercentage(100);
        infoTable.setSpacingBefore(10);
        
        addTableCell(infoTable, "Stock Code", true);
        addTableCell(infoTable, result.getStkcd(), false);
        addTableCell(infoTable, "Risk Level", true);
        addTableCell(infoTable, result.getLevel(), false);
        addTableCell(infoTable, "Risk Probability", true);
        addTableCell(infoTable, String.format("%.2f%%", result.getRiskProbability() * 100), false);
        
        document.add(infoTable);

        // SHAP 分析部分
        document.add(new Paragraph("\nCore Indicator Contribution (SHAP Analysis):", FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14)));
        PdfPTable shapTable = new PdfPTable(3);
        shapTable.setWidthPercentage(100);
        shapTable.setSpacingBefore(10);
        
        addTableCell(shapTable, "Indicator", true);
        addTableCell(shapTable, "SHAP Value", true);
        addTableCell(shapTable, "Impact", true);

        Map<String, Double> shap = result.getShapAnalysis();
        if (shap != null) {
            for (Map.Entry<String, Double> entry : shap.entrySet()) {
                addTableCell(shapTable, entry.getKey(), false);
                addTableCell(shapTable, String.format("%.4f", entry.getValue()), false);
                addTableCell(shapTable, entry.getValue() > 0 ? "Increase Risk" : "Decrease Risk", false);
            }
        }
        document.add(shapTable);

        // AI 专家点评
        if (result.getCommentary() != null && !result.getCommentary().isEmpty()) {
            document.add(new Paragraph("\nAI Expert Commentary:", FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14)));
            Paragraph commentary = new Paragraph(result.getCommentary(), FontFactory.getFont(FontFactory.HELVETICA, 11));
            commentary.setSpacingBefore(10);
            document.add(commentary);
        }

        // 脚注
        Paragraph footer = new Paragraph("\n\nGenerated by LightGBM Financial Risk Warning System", FontFactory.getFont(FontFactory.HELVETICA, 8));
        footer.setAlignment(Element.ALIGN_RIGHT);
        document.add(footer);

        document.close();
        return out.toByteArray();
    }

    private void addTableCell(PdfPTable table, String text, boolean isHeader) {
        PdfPCell cell = new PdfPCell(new Phrase(text, FontFactory.getFont(isHeader ? FontFactory.HELVETICA_BOLD : FontFactory.HELVETICA, 10)));
        cell.setPadding(5);
        if (isHeader) {
            cell.setBackgroundColor(Color.LIGHT_GRAY);
        }
        table.addCell(cell);
    }
}
